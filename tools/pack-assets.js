#!/usr/bin/env node
/**
 * Bundles the loose content of content-src/ into assets/packs.js. The game uses it only when the content
 * folder cannot be read (page opened straight from disk, or published as a single file).
 *
 * Usage: node tools/pack-assets.js   (also run by tools/build.js)
 * Needs: Node.js only.
 * Output: `window.IK_PACKS = [{ name: 'bundled', files: { '<relative path>': '<base64 data>' } }]`
 */
const fs = require('fs'),
  path = require('path');

const sourceDir = path.join(__dirname, '..', 'content-src'),
  outputDir = path.join(__dirname, '..', 'assets'),
  base64ByPath = {};

/**
 * Recursively reads every file under `directory` into `base64ByPath`, keyed by its '/'-separated
 * path relative to content-src/. Generated manifest.json / packs.js files are skipped.
 * @param {string} directory absolute directory to scan
 * @param {string} relativeDir its path relative to content-src/ ('' for the root)
 */
const collectFiles = (directory, relativeDir) => {
  for (const name of fs.readdirSync(directory)) {
    const diskPath = path.join(directory, name),
      relativePath = relativeDir ? relativeDir + '/' + name : name;
    if (fs.statSync(diskPath).isDirectory()) collectFiles(diskPath, relativePath);
    else if (!/^(manifest\.json|packs\.js)$/i.test(name))
      base64ByPath[relativePath] = fs.readFileSync(diskPath).toString('base64');
  }
};
collectFiles(sourceDir, '');
fs.mkdirSync(outputDir, { recursive: true });
fs.writeFileSync(
  path.join(outputDir, 'packs.js'),
  '/* generated by tools/pack-assets.js */\nwindow.IK_PACKS = ' +
    JSON.stringify([{ name: 'bundled', files: base64ByPath }]) +
    ';\n'
);
console.log('packs: bundled (' + Object.keys(base64ByPath).length + ' files)');
